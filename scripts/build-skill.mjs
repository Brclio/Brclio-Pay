import './sync-environment-docs.mjs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const variants = ['brclio-pay-integrate', 'brclio-alipay-integrate', 'brclio-wechatpay-integrate'];
const names = ['SKILL.md', 'references/integration.md', 'scripts/inspect-platform.mjs', 'scripts/integration-client.mjs', 'assets/payment-client.mjs', 'assets/webhook-handler.mjs', 'assets/payment-completion.mjs'];
const bundles = {};
for (const variant of variants) {
  const directory = path.join(root, 'skills', variant);
  await mkdir(path.join(directory, 'assets'), { recursive: true });
  for (const name of ['payment-client.mjs', 'webhook-handler.mjs', 'payment-completion.mjs']) {
    await writeFile(path.join(directory, 'assets', name), await readFile(path.join(root, 'examples', name)));
  }
  await writeFile(path.join(directory, 'references/integration.md'), await readFile(path.join(root, 'docs/integration.md')));
  const files = {};
  for (const name of names) files[`${variant}/${name}`] = await readFile(path.join(directory, name), 'utf8');
  bundles[variant] = files;
}
// Deployment is deliberately separate from the three scoped product-integration variants.
const deploymentVariant = 'brclio-pay-deploy';
const deploymentDirectory = path.join(root, 'skills', deploymentVariant);
await mkdir(path.join(deploymentDirectory, 'references'), { recursive: true });
const deploymentNames = ['SKILL.md', 'agents/openai.yaml'];
const bundledDocs = new Set(['deployment', 'environment-variables', 'merchant-setup']);
for (const name of bundledDocs) {
  let source = await readFile(path.join(root, 'docs', `${name}.md`), 'utf8');
  source = source.replace(/\]\(\.\.\/examples\/deployment\/([^)]*)\)/g, ']($1)')
    .replace(/\]\(\.\.\/skills\/brclio-pay-deploy\/SKILL\.md\)/g, '](../SKILL.md)')
    .replace(/\]\(([^:/)#]+)\.md(#[^)]*)?\)/g, (match, target, anchor = '') => bundledDocs.has(target) ? match : `](https://github.com/Brclio/Brclio-Pay/blob/main/docs/${target}.md${anchor})`);
  const target = `references/${name}.md`;
  await writeFile(path.join(deploymentDirectory, target), source);
  deploymentNames.push(target);
}
for (const name of ['setup-input.example.json', 'setup-alipay.example.json', 'setup-wechat.example.json']) {
  const target = `references/${name}`;
  await writeFile(path.join(deploymentDirectory, target), await readFile(path.join(root, 'examples/deployment', name)));
  deploymentNames.push(target);
}
const deploymentFiles = {};
for (const name of deploymentNames) deploymentFiles[`${deploymentVariant}/${name}`] = await readFile(path.join(deploymentDirectory, name), 'utf8');
await writeFile(path.join(root, 'src/skill-data.ts'), '// Generated by scripts/build-skill.mjs; do not edit by hand.\nexport const skillVariants: Record<string, Record<string, string>> = ' + JSON.stringify(bundles, null, 2) + ';\nexport const skillFiles = skillVariants[\'brclio-pay-integrate\'];\nexport const deploymentSkillFiles: Record<string, string> = ' + JSON.stringify(deploymentFiles, null, 2) + ';\n');
